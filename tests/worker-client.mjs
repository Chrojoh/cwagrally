import assert from 'node:assert/strict';
import { GenerationClient } from '../src/core/worker-client.js';
const workers=[];
const client=new GenerationClient(()=>{
  const worker={terminated:false,postMessage(data){this.sent=data;},terminate(){this.terminated=true;}};
  workers.push(worker);return worker;
});
const first=client.run('cwags',{levelId:'S'});
const cancelled=assert.rejects(first,{name:'AbortError'});
const oldWorker=workers[0];
const second=client.run('cwags',{levelId:'A'});
await cancelled;
assert.equal(oldWorker.terminated,true,'obsolete CPU search is terminated');
oldWorker.onmessage({data:{id:oldWorker.sent.id,course:'stale'}});
const current=workers[1];
current.onmessage({data:{id:current.sent.id,course:'current'}});
assert.equal(await second,'current','late results cannot replace the active request');
const third=client.run('cwags',{});
assert.equal(workers.length,2,'successful worker retains search history');
const rejection=assert.rejects(third,{name:'AbortError'});
client.cancel();await rejection;
const failed=client.run('cwags',{});
const errorCheck=assert.rejects(failed,/could not start/);
workers[2].onerror();await errorCheck;
assert.equal(workers[2].terminated,true);
const recovered=client.run('cwags',{},'upgrade');
workers[3].onmessage({data:{id:workers[3].sent.id,result:{course:'upgraded'}}});
assert.deepEqual(await recovered,{course:'upgraded'});
console.log('Worker cancellation, stale results, history retention and error recovery PASS');
